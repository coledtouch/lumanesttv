// Writes tests/BrowseCases.brs from docs/browse-cases.json, the Movies & Series test cases every Tuner app runs
// (docs/browse.md, "Test cases"). The BrightScript tests can't read files from the repository, so the cases are
// compiled into a function that BrowseLogicTests.brs calls.
//   node tools/browse-cases.mjs           writes the file (npm run cases)
//   node tools/browse-cases.mjs --check   fails when the file is out of date (part of npm run check)
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(app, '../../docs/browse-cases.json');
const target = path.join(app, 'tests', 'BrowseCases.brs');

// Characters written as Chr(n): controls, and spaces and marks that are invisible or easy to mistake in source.
function special(code) {
  return code < 0x20 || (code >= 0x7f && code <= 0xa0) || code === 0xad || (code >= 0x300 && code <= 0x36f) ||
    code === 0x1680 || code === 0x180e || (code >= 0x2000 && code <= 0x200f) || (code >= 0x2028 && code <= 0x202f) ||
    code === 0x205f || code === 0x3000 || code === 0xfeff;
}

// A BrightScript string expression. BrightScript strings have no escapes: a quote is doubled. With ascii, every
// character beyond ASCII is written as Chr(n) too (a tmdb case's JSON text, which holds look-alike digits).
function str(value, ascii = false) {
  if (typeof value !== 'string') throw new Error('expected a string, got ' + JSON.stringify(value));
  const parts = [];
  let plain = '';
  for (const ch of value) {
    const code = ch.codePointAt(0);
    if (special(code) || (ascii && code > 0x7e)) {
      if (code > 0xffff) throw new Error('Chr takes a code up to U+FFFF: ' + JSON.stringify(value));
      if (plain) parts.push('"' + plain + '"');
      plain = '';
      parts.push('Chr(' + code + ')');
    } else {
      plain += ch === '"' ? '""' : ch;
    }
  }
  if (plain || !parts.length) parts.push('"' + plain + '"');
  return parts.join(' + ');
}

function bool(value) {
  if (typeof value !== 'boolean') throw new Error('expected true or false, got ' + JSON.stringify(value));
  return String(value);
}

function strings(value) {
  if (!Array.isArray(value)) throw new Error('expected an array, got ' + JSON.stringify(value));
  return '[' + value.map(str).join(', ') + ']';
}

function line(c) {
  const fields = [['kind', str(c.kind)]];
  if (c.kind === 'category') {
    fields.push(['name', str(c.name)], ['foreign', bool(c.foreign)]);
  } else if (c.kind === 'normalize') {
    fields.push(['input', str(c.input)], ['title', str(c.title)], ['year', str(c.year)]);
  } else if (c.kind === 'usa') {
    fields.push(['category', Array.isArray(c.category) ? strings(c.category) : str(c.category)],
      ['origin', c.origin === null ? 'invalid' : strings(c.origin)], ['expect', bool(c.expect)]);
  } else if (c.kind === 'tmdb') {
    // json is the provider's row as JSON text, which the test reads with ParseJson as the catalog task does; expect is
    // the id, or invalid for none (null).
    if (c.expect !== null && !/^[1-9][0-9]{0,11}$/.test(c.expect)) throw new Error('expected an id or null, got ' + JSON.stringify(c.expect));
    fields.push(['json', str(c.json, true)], ['expect', c.expect === null ? 'invalid' : str(c.expect)]);
  } else {
    throw new Error('unknown case kind ' + JSON.stringify(c.kind));
  }
  return '    c.Push({' + fields.map(([key, value]) => '"' + key + '": ' + value).join(', ') + '})';
}

function generate() {
  const cases = JSON.parse(fs.readFileSync(source, 'utf8'));
  if (!Array.isArray(cases) || !cases.length) throw new Error(source + ' holds no cases');
  return [
    "' Generated by tools/browse-cases.mjs from docs/browse-cases.json. Don't edit it: change the JSON, then run",
    "' npm run cases. npm run check fails while this file is out of date.",
    '',
    "' The Movies & Series test cases every Tuner app runs (docs/browse.md, \"Test cases\"), for BrowseLogicTests.brs.",
    'function browseCases() as object',
    '    c = []',
    ...cases.map(line),
    '    return c',
    'end function',
    '',
  ].join('\n');
}

const text = generate();
const relative = path.relative(app, target);
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error(relative + ' is out of date with docs/browse-cases.json. Run npm run cases.');
    process.exit(1);
  }
  console.log(relative + ' matches docs/browse-cases.json.');
} else {
  fs.writeFileSync(target, text);
  console.log('Wrote ' + relative + '.');
}
