// Writes tests/ExtrasCases.brs from docs/extras-cases.json, the subtitle, trailer and live category test cases every
// Tuner component runs (docs/extras.md, "Test cases"). Roku runs the live_category cases; the others are the server's
// (OpenSubtitles and TMDB answers) and the WebVTT reader's, which Roku doesn't have: it draws subtitles itself.
// The BrightScript tests can't read files from the repository, so the cases are compiled into a function that
// ExtrasLogicTests.brs calls.
//   node tools/extras-cases.mjs           writes the file (npm run cases)
//   node tools/extras-cases.mjs --check   fails when the file is out of date (part of npm run check)
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(app, '../../docs/extras-cases.json');
const target = path.join(app, 'tests', 'ExtrasCases.brs');
const KINDS = ['live_category'];

// A BrightScript string expression in plain ASCII. BrightScript strings have no escapes: a quote is doubled, and every
// control character and every character beyond ASCII is written as Chr(n) with its code point (Chr takes code points
// beyond U+FFFF too, such as an emoji), so no invisible or look-alike character is ever typed into the file.
function str(value) {
  if (typeof value !== 'string') throw new Error('expected a string, got ' + JSON.stringify(value));
  const parts = [];
  let plain = '';
  for (const ch of value) {
    const code = ch.codePointAt(0);
    if (code < 0x20 || code > 0x7e) {
      if (code >= 0xd800 && code <= 0xdfff) throw new Error('a lone surrogate has no Chr: ' + JSON.stringify(value));
      if (plain) parts.push('"' + plain + '"');
      plain = '';
      parts.push('Chr(' + code + ')');
    } else {
      plain += ch === '"' ? '""' : ch;
    }
  }
  if (plain || !parts.length) parts.push('"' + plain + '"');
  return parts.join(' + ');
}

function bool(value) {
  if (typeof value !== 'boolean') throw new Error('expected true or false, got ' + JSON.stringify(value));
  return String(value);
}

function line(c) {
  if (c.kind === 'live_category') {
    return '    c.Push({"kind": ' + str(c.kind) + ', "name": ' + str(c.name) + ', "hidden": ' + bool(c.hidden) + '})';
  }
  throw new Error('unknown case kind ' + JSON.stringify(c.kind));
}

function generate() {
  const cases = JSON.parse(fs.readFileSync(source, 'utf8'));
  if (!Array.isArray(cases) || !cases.length) throw new Error(source + ' holds no cases');
  const used = cases.filter(c => KINDS.includes(c && c.kind));
  if (!used.length) throw new Error(source + ' holds no ' + KINDS.join(' or ') + ' cases');
  return [
    "' Generated by tools/extras-cases.mjs from docs/extras-cases.json. Don't edit it: change the JSON, then run",
    "' npm run cases. npm run check fails while this file is out of date.",
    '',
    "' The hidden live category cases every Tuner app runs (docs/extras.md, \"Test cases\"), for ExtrasLogicTests.brs.",
    'function extrasCases() as object',
    '    c = []',
    ...used.map(line),
    '    return c',
    'end function',
    '',
  ].join('\n');
}

const text = generate();
const relative = path.relative(app, target);
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error(relative + ' is out of date with docs/extras-cases.json. Run npm run cases.');
    process.exit(1);
  }
  console.log(relative + ' matches docs/extras-cases.json.');
} else {
  fs.writeFileSync(target, text);
  console.log('Wrote ' + relative + '.');
}
